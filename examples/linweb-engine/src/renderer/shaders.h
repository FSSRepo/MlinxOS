    "    float alpha = 1.0 - smoothstep(-1.0, 1.0, dist);\n"
    "    gl_FragColor = vec4(finalColor.rgb, finalColor.a * alpha);\n"
    "  } else {\n"
    "    gl_FragColor = finalColor;\n"
    "  }\n"
    "}\n";

