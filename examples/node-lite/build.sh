#!/bin/bash
# Cross-compiles node-lite with the Buildroot toolchain and installs it in the rootfs, as /usr/bin/node-lite,
# together with its examples and tests under /root/node-lite (linweb's System > Node Lite runs them from there).
#   bash build.sh [BUILDROOT_DIR]
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
BUILDROOT_DIR=${1:-${BUILDROOT_DIR:-"$SCRIPT_DIR/../../../wayland-os"}}
BUILD_DIR=${BUILD_DIR:-"$SCRIPT_DIR/build-target"}

if [[ ! -f "$BUILDROOT_DIR/output/host/share/buildroot/toolchainfile.cmake" ]]; then
    echo "ERROR: Buildroot toolchain not found at $BUILDROOT_DIR" >&2
    echo "Usage: bash build.sh [BUILDROOT_DIR]" >&2
    exit 1
fi

BUILDROOT_DIR=$(cd "$BUILDROOT_DIR" && pwd)
if [[ -x "$BUILDROOT_DIR/output/host/bin/cmake" ]]; then
    CMAKE="$BUILDROOT_DIR/output/host/bin/cmake"
elif command -v cmake >/dev/null 2>&1; then
    CMAKE=$(command -v cmake)
else
    echo "ERROR: CMake was not found in Buildroot or on the host." >&2
    exit 1
fi

"$CMAKE" -S "$SCRIPT_DIR" -B "$BUILD_DIR" \
    -DCMAKE_TOOLCHAIN_FILE="$BUILDROOT_DIR/output/host/share/buildroot/toolchainfile.cmake" \
    -DCMAKE_BUILD_TYPE=Release
"$CMAKE" --build "$BUILD_DIR" --target node-lite --parallel "$(nproc)"

TARGET="$BUILDROOT_DIR/output/target"
STRIP=$(ls "$BUILDROOT_DIR"/output/host/bin/*-linux-gnu-strip 2>/dev/null | head -1 || true)
install -D -m 0755 "$BUILD_DIR/node-lite" "$TARGET/usr/bin/node-lite"
if [[ -n "$STRIP" ]]; then "$STRIP" "$TARGET/usr/bin/node-lite"; fi

# examples, tests and the README that index-docs.js reads; files generated by running the examples stay out
DEST="$TARGET/root/node-lite"
rm -rf "$DEST"
install -d "$DEST"
(cd "$SCRIPT_DIR" && tar cf - --exclude=vectors.json --exclude=docs.vec.json README.md example tests) | tar xf - -C "$DEST"

echo "Installed /usr/bin/node-lite ($(du -h "$TARGET/usr/bin/node-lite" | cut -f1)) and /root/node-lite."
